    // Método auxiliar para não repetirmos código de cor e fonte dos botões
    private void estilizarBotao(JButton botao, String corHex) {
        botao.setBackground(Color.decode(corHex));
        botao.setForeground(Color.WHITE);
        botao.setFont(new Font("SansSerif", Font.BOLD, 18));
        botao.setFocusPainted(false);
    }
    
    
